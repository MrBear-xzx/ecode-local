const GENERATED_HEADER = [
  '// Generated by Ecode Local. Do not edit this file directly.',
  '// Regenerate it with "Ecode: 刷新 AI Coding 支持".',
  '',
].join('\n');

export function generateGlobalDeclarations(): string {
  const nested = new NestedDeclarationWriter();
  const objectBlocks = ECODE_API_OBJECTS.map(info => {
    const entries = ECODE_API_ENTRIES.filter(entry => entry.object === info.object);
    const members = entries.map(entry => apiMember(entry, nested));
    return [
      jsDoc(info.description, info.officialUrl),
      `interface ${info.object}Api {`,
      ...members.map(member => indent(member)),
      '}',
      '',
    ].join('\n');
  });
  const globals = ECODE_API_OBJECTS.flatMap(info => [
    jsDoc(info.description, info.officialUrl),
    `declare const ${info.object}: ${info.object}Api;`,
  ]);
  const windowMembers = ECODE_API_OBJECTS
    .map(info => `  ${info.object}: ${info.object}Api;`);

  return ensureTrailingNewline([
    GENERATED_HEADER,
    ...nested.lines,
    ...objectBlocks,
    ...globals,
    '',
    'interface Window {',
    ...windowMembers,
    '}',
  ].join('\n'));
}

export function generateComponentDeclarations(): string {
  const nested = new NestedDeclarationWriter();
  const propInterfaces = ECODE_COMPONENT_ENTRIES.map(entry =>
    componentPropsInterface(entry, nested));
  const namespaces = ['ecCom', 'antd'] as const;
  const namespaceBlocks = namespaces.map(namespace => {
    const entries = ECODE_COMPONENT_ENTRIES
      .filter(entry => entry.namespace === namespace);
    const members = entries.map(entry =>
      `  readonly ${quoteProperty(entry.name)}: EcodeAiComponent<${componentPropsName(entry)}>;`);
    const exports = entries.map(entry =>
      `  export const ${entry.name}: EcodeAiComponent<${componentPropsName(entry)}>;`);
    return [
      `interface ${pascalCase(namespace)}ComponentLibrary {`,
      ...members,
      '}',
      '',
      `declare const ${namespace}: ${pascalCase(namespace)}ComponentLibrary;`,
      '',
      `declare module '${namespace}' {`,
      ...exports,
      '}',
      '',
    ].join('\n');
  });

  return ensureTrailingNewline([
    GENERATED_HEADER,
    'interface EcodeAiComponent<Props = Record<string, unknown>> {',
    '  (props: Props): unknown;',
    '}',
    '',
    ...nested.lines,
    ...propInterfaces,
    ...namespaceBlocks,
    'interface Window {',
    '  ecCom: EcComComponentLibrary;',
    '  antd: AntdComponentLibrary;',
    '}',
  ].join('\n'));
}

