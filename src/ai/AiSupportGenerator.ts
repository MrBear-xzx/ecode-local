export function generateWorkspaceComponents(
  workspaceRoot: string,
  calls: readonly IndexedEcodeComponentCall[],
): string {
  const groups = new Map<string, IndexedEcodeComponentCall[]>();
  for (const call of calls) {
    const key = `${call.appId}\0${call.name}`;
    const group = groups.get(key) ?? [];
    group.push(call);
    groups.set(key, group);
  }
  const sections = [...groups.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .flatMap(([, group]) => {
      const first = group[0];
      const definitions = group.filter(call => call.kind === 'definition');
      const references = group.filter(call => call.kind === 'reference');
      return [
        `## ${escapeMarkdown(first.name)}`,
        '',
        `- appId: \`${escapeCode(first.appId)}\``,
        `- 组件名: \`${escapeCode(first.name)}\``,
        `- 定义: ${locationList(workspaceRoot, definitions)}`,
        `- 引用: ${locationList(workspaceRoot, references)}`,
        '',
      ];
    });
  return ensureTrailingNewline([
    '# Ecode 工作区组件',
    '',
    '由 Ecode Local 从 `ecode/` 内的 `ecodeSDK.setCom/getCom` 调用生成。',
    '',
    ...(sections.length > 0
      ? sections
      : ['当前 `ecode/` 源码中尚未发现静态组件注册或引用。', '']),
  ].join('\n'));
}

export function generateWorkspaceFormMetadata(
  files: readonly CachedFileFormMetadata[],
): string {
  const groups = new Map<string, {
    context: FormContext;
    paths: string[];
  }>();
  for (const file of files) {
    for (const context of file.contexts) {
      const key = JSON.stringify(context);
      const group = groups.get(key) ?? { context, paths: [] };
      group.paths.push(`ecode/${file.path.replace(/\\/g, '/')}`);
      groups.set(key, group);
    }
  }
  const sections = [...groups.values()]
    .sort((left, right) =>
      formContextTitle(left.context).localeCompare(formContextTitle(right.context)))
    .flatMap(group => [
      `## ${formContextTitle(group.context)}`,
      '',
      `关联源码：${group.paths
        .sort((left, right) => left.localeCompare(right))
        .map(value => `\`${escapeCode(value)}\``)
        .join('、')}`,
      '',
      ...group.context.tables.flatMap(table =>
        formTableSection(table)),
    ]);
  return ensureTrailingNewline([
    '# Ecode 工作区表单字段',
    '',
    '由 Ecode Local 根据全量拉取获得的表单上下文与字段缓存生成，供 AI 在离线编辑时理解字段含义。',
    '',
    '## 字段定位规则',
    '',
    '- `WfForm.convertFieldNameToId("field_name")` 和 `ModeForm.convertFieldNameToId("field_name")` 默认定位主表 `main`。',
    '- 显式传入 `"detail_N"` 时，只定位对应明细表；无法静态确定表标识时不要猜测。',
    '- `field110_3` 表示字段 `field110` 的明细行实例，字段定义仍以 `field110` 查询。',
    '',
    ...(sections.length > 0
      ? sections
      : ['当前缓存中尚无可关联到源码文件的表单字段元数据。', '']),
  ].join('\n'));
}

function formContextTitle(context: FormContext): string {
  const kind = context.kind === 'workflow'
    ? '流程表单'
    : context.kind === 'mode' ? '建模表单' : '共享表单';
  const ids = [
    context.workflowId ? `workflowId ${context.workflowId}` : undefined,
    context.requestId ? `requestId ${context.requestId}` : undefined,
    context.modeId ? `modeId ${context.modeId}` : undefined,
    context.formId ? `formId ${context.formId}` : undefined,
  ].filter(Boolean);
  return ids.length > 0 ? `${kind}（${ids.join('，')}）` : kind;
}

function formTableSection(table: FormTable): string[] {
  const title = table.title
    || table.tableName
    || (table.mark === 'main' ? '主表' : table.mark);
  return [
    `### ${escapeMarkdown(table.mark)} — ${escapeMarkdown(title)}`,
    '',
    ...(table.tableName
      ? [`数据库表：\`${escapeCode(table.tableName)}\``, '']
      : []),
    '| 标识 | 中文名 | 数据库字段 | 类型 | 查看 | 编辑 | 必填 |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...table.fields.map(field => formFieldRow(field)),
    '',
  ];
}

function formFieldRow(field: FormField): string {
  const type = [
    field.htmlType ? `htmlType ${field.htmlType}` : undefined,
    field.detailType ? `detailType ${field.detailType}` : undefined,
    field.dbType,
  ].filter(Boolean).join(' / ');
  return [
    `\`field${escapeCode(field.id)}\``,
    escapeTableCell(field.label),
    field.name ? `\`${escapeCode(field.name)}\`` : '',
    escapeTableCell(type),
    booleanMetadata(field.isView),
    booleanMetadata(field.isEdit),
    booleanMetadata(field.isMandatory),
  ].join(' | ').replace(/^/, '| ').replace(/$/, ' |');
}

function booleanMetadata(value: boolean | undefined): string {
  return value === undefined ? '' : value ? '是' : '否';
}

function escapeTableCell(value: string): string {
  return escapeMarkdown(value)
    .replace(/\|/g, '\\|')
    .replace(/\r?\n/g, '<br>');
}

export function normalizeType(rawType: string): string {
  const value = rawType
    .replace(/\s+/g, ' ')
    .trim();
  if (!value) {
    return 'unknown';
  }
  if (/^(any|unknow|未知)$/i.test(value)) {
    return 'unknown';
  }
  if (/^(string|number|boolean|void|never|null|undefined|unknown|Date)$/i.test(value)) {
    const lower = value.toLowerCase();
    return lower === 'date' ? 'Date' : lower;
  }
  if (/^(bool)$/i.test(value)) {
    return 'boolean';
  }
  if (/^(int|integer|float|double)$/i.test(value)) {
    return 'number';
  }
  if (/^(object|map|json)$/i.test(value)) {
    return 'Record<string, unknown>';
  }
  if (/^(array|list|集合|数组)$/i.test(value)) {
    return 'unknown[]';
  }
  if (/^(function|func|callback)$/i.test(value)) {
    return '(...args: unknown[]) => unknown';
  }
  if (/^function\s*\(([^)]*)\)$/i.test(value)) {
    const match = /^function\s*\(([^)]*)\)$/i.exec(value);
    const names = (match?.[1] ?? '')
      .split(',')
      .map(item => item.trim())
      .filter(Boolean)
      .map((item, index) => `${safeIdentifier(item, `arg${index + 1}`)}: unknown`);
    return `(${names.join(', ')}) => unknown`;
  }
  if (value.includes('=>')) {
    return /^\(\s*\)\s*=>\s*void$/i.test(value)
      ? '() => void'
      : '(...args: unknown[]) => unknown';
  }
  if (/\b(React|Element|Node|组件)\b/i.test(value)) {
    return 'unknown';
  }
  const arrayMatch = /^(?:Array|array)\s*<(.+)>$/i.exec(value);
  if (arrayMatch) {
    return `Array<${normalizeType(arrayMatch[1])}>`;
  }
  const suffixArray = /^(.+)\[\]$/.exec(value);
  if (suffixArray) {
    return `${parenthesizeUnion(normalizeType(suffixArray[1]))}[]`;
  }
  const unionParts = value.split(/\s*(?:\||\bor\b)\s*/i);
  if (unionParts.length > 1) {
    const normalized = [...new Set(unionParts.map(normalizeType))];
    return normalized.includes('unknown')
      ? 'unknown'
      : normalized.map(parenthesizeFunction).join(' | ');
  }
  if (/^(['"]).*\1$/.test(value) || /^-?\d+(?:\.\d+)?$/.test(value)) {
    return value;
  }
  return 'unknown';
}

class NestedDeclarationWriter {
  readonly lines: string[] = [];
  private readonly names = new Set<string>();

  typeForSchema(name: string, schema: NestedSchema): string {
    if (schema.itemProperties) {
      const itemName = `${name}Item`;
      return `${this.interfaceForProperties(itemName, schema.itemProperties)}[]`;
    }
    if (schema.properties) {
      return this.interfaceForProperties(name, schema.properties);
    }
    return 'Record<string, unknown>';
  }

  private interfaceForProperties(
    name: string,
    properties: readonly NestedProperty[],
  ): string {
    if (properties.length === 0) {
      return 'Record<string, unknown>';
    }
    if (!this.names.has(name)) {
      this.names.add(name);
      const members = properties.map(property => {
        let type = normalizeType(property.type);
        if (property.properties) {
          type = this.interfaceForProperties(
            `${name}${pascalCase(property.name)}`,
            property.properties,
          );
        } else if (property.itemProperties) {
          const itemType = this.interfaceForProperties(
            `${name}${pascalCase(property.name)}Item`,
            property.itemProperties,
          );
          type = `${itemType}[]`;
        }
        return [
          jsDoc(property.description),
          `${quoteProperty(property.name)}${property.required ? '' : '?'}: ${type};`,
        ].join('\n');
      });
      this.lines.push([
        `interface ${name} {`,
        ...members.map(member => indent(member)),
        '}',
        '',
      ].join('\n'));
    }
    return name;
  }
}

function apiMember(
  entry: EcodeApiEntry,
  nested: NestedDeclarationWriter,
): string {
  const parameterLines = entry.parameters.map(parameter =>
    `@param ${parameter.name} ${parameter.description} 原始类型：${parameter.type}`);
  const documentation = jsDoc(
    [entry.description, ...parameterLines].join('\n'),
    entry.officialUrl,
  );
  if (entry.kind === 'property') {
    const separator = entry.signature.indexOf(':');
    const rawType = separator >= 0 ? entry.signature.slice(separator + 1) : '';
    return `${documentation}\nreadonly ${quoteProperty(entry.name)}: ${normalizeType(rawType)};`;
  }
  const nestedTypes = new Map(
    getApiNestedSchemas(entry).map(item => [
      item.parameterName,
      nested.typeForSchema(
        `${pascalCase(entry.object)}${pascalCase(entry.name)}${pascalCase(item.parameterName)}`,
        item.schema,
      ),
    ]),
  );
  const parameters = entry.parameters.map((parameter, index) => {
    const hasRequiredAfter = entry.parameters
      .slice(index + 1)
      .some(candidate => candidate.required);
    const optional = !parameter.required && !hasRequiredAfter;
    let type = nestedTypes.get(parameter.name) ?? normalizeType(parameter.type);
    if (!parameter.required && hasRequiredAfter) {
      type = `${parenthesizeFunction(type)} | undefined`;
    }
    return `${safeIdentifier(parameter.name, `arg${index + 1}`)}${optional ? '?' : ''}: ${type}`;
  });
  return [
    documentation,
    `${quoteProperty(entry.name)}(${parameters.join(', ')}): ${methodReturnType(entry.signature)};`,
  ].join('\n');
}

function componentPropsInterface(
  entry: EcodeComponentEntry,
  nested: NestedDeclarationWriter,
): string {
  const nestedTypes = new Map(
    getComponentNestedSchemas(entry).map(item => [
      item.propName,
      nested.typeForSchema(
        `${componentPropsName(entry)}${pascalCase(item.propName)}`,
        item.schema,
      ),
    ]),
  );
  const members = entry.props.map(prop => [
    jsDoc([
      prop.description,
      prop.defaultValue ? `默认值：${prop.defaultValue}` : '',
      `原始类型：${prop.type}`,
    ].filter(Boolean).join('\n')),
    `${quoteProperty(prop.name)}${prop.required ? '' : '?'}: ${
      nestedTypes.get(prop.name) ?? normalizeType(prop.type)
    };`,
  ].join('\n'));
  return [
    jsDoc(`${entry.title}\n${entry.description}`, entry.officialUrl),
    `interface ${componentPropsName(entry)} {`,
    ...members.map(member => indent(member)),
    '}',
    '',
  ].join('\n');
}

function componentPropsName(entry: EcodeComponentEntry): string {
  return `${pascalCase(entry.namespace)}${pascalCase(entry.name)}Props`;
}

function methodReturnType(signature: string): string {
  const match = /\)\s*:\s*(.+)$/.exec(signature);
  return normalizeType(match?.[1] ?? '');
}

function locationList(
  workspaceRoot: string,
  calls: readonly IndexedEcodeComponentCall[],
): string {
  if (calls.length === 0) {
    return '无';
  }
  return calls.map(call => {
    const relative = path.relative(workspaceRoot, call.uri.fsPath)
      .split(path.sep)
      .join('/');
    return `\`${escapeCode(relative)}:${call.range.start.line + 1}\``;
  }).join('、');
}

function jsDoc(description: string, url?: string): string {
  const lines = description
    .replace(/\*\//g, '*\\/')
    .split(/\r?\n/);
  if (url) {
    lines.push(`来源：${url}`);
  }
  return ['/**', ...lines.map(line => ` * ${line}`), ' */'].join('\n');
}

function indent(value: string): string {
  return value.split('\n').map(line => `  ${line}`).join('\n');
}

function pascalCase(value: string): string {
  const result = value
    .replace(/[^A-Za-z0-9_$]+(.)?/g, (_match, next: string | undefined) =>
      next?.toUpperCase() ?? '')
    .replace(/^[a-z]/, character => character.toUpperCase());
  return /^[A-Za-z_$]/.test(result) ? result : `Ecode${result}`;
}

function quoteProperty(value: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(value)
    ? value
    : JSON.stringify(value);
}

function safeIdentifier(value: string, fallback: string): string {
  const cleaned = value.replace(/^\.\.\./, '');
  return /^[A-Za-z_$][\w$]*$/.test(cleaned) ? cleaned : fallback;
}

function parenthesizeUnion(type: string): string {
  return type.includes('|') ? `(${type})` : type;
}

function parenthesizeFunction(type: string): string {
  return type.includes('=>') ? `(${type})` : type;
}

function escapeMarkdown(value: string): string {
  return value.replace(/([\\`*_{}[\]()#+\-.!])/g, '\\$1');
}

function escapeCode(value: string): string {
  return value.replace(/`/g, '\\`');
}

function ensureTrailingNewline(value: string): string {
  return `${value.replace(/\s+$/, '')}\n`;
}
